// Code-Mem single-file bundle builder.
//
// cm is distributed as ONE self-contained CommonJS file (`bin/cm`) that
// install.sh / `cm update` fetch via curl. The source of truth lives in
// `src/` as ordered fragments which share a single scope (the classic
// concatenation pattern for a CLI that must ship as a single file).
//
// This script concatenates them in canonical order and writes the executable
// `bin/cm`. Rerun after editing any src/ fragment:
//
//   node build/bundle.mjs
//
// Fragment order must follow the monolith's original top-level order so lower
// const/let initializations run before use; function declarations are hoisted.
import { readFileSync, writeFileSync, chmodSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Canonical order == the monolith's original line order (see src/README).
const ORDER = [
  "src/globals.js",
  "src/fsutil.js",
  "src/config.js",    // cm config: persistent settings (global/project env files)
  "src/capture.js",
  "src/db.js",        // od() references ensureMessagesSearchTables (db.js)
  "src/cognitive.js", // evidence, temporal belief lifecycle, gate and working set
  "src/scanner.js",
  "src/embed.js",
  "src/graph.js",
  "src/semantic.js",  // buildAutoQuery
  "src/help.js",      // gl / glFull
  "src/update.js",
  "src/plan.js",      // parseArgs
  "src/storage.js",
  "src/retrieval.js",
  "src/context.js",
  "src/harness.js",      // harness discovery, settings metadata, local skill/command integration
  "src/llm.js",          // read-only harness-backed semantic bridge
  "src/jev.js",          // optional Jev typed-decision client + credit alerts
  "src/findex.js",       // file index: question -> answering file (+ Jev re-rank)
  "src/memory-ops.js",
  "src/mcp.js",         // cm mcp stdio server
  "src/graph-export.js", // graph exports and community operations
  "src/logic.js",        // plain-language logic view (parts + flows)
  "src/docs.js",         // documentation view (topics + typed document relations)
  "src/entities.js",
  "src/workflow.js",    // unified full-repository indexing workflow
  "src/graph-service.js", // global per-user graph service lifecycle + project registry
  "src/graph-server.js", // local graph HTML + harness chat bridge
  "src/main.js",      // main() + main().catch
];

const shebang = "#!/usr/bin/env node";
const banner = [
  shebang,
  "// cm — Code-Mem Tool (single-file bundle).",
  "// Source of truth: src/*.js — regenerate with `node build/bundle.mjs`.",
  "// Do NOT edit this file by hand.",
  "",
].join("\n");

const body = ORDER.map((f) => readFileSync(join(root, f), "utf-8").trimEnd()).join("\n\n");

const out = join(root, "bin", "cm");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, banner + "\n" + body + "\n", "utf-8");
chmodSync(out, 0o755);
console.log(`Bundle written: ${out} (${orderSize(body)} bytes, ${ORDER.length} fragments)`);

// Publish the SHA-256 manifest consumed by `cm update`'s integrity gate
// (update.js fetches bin/cm.sha256 next to bin/cm).
import { createHash } from "node:crypto";
const digest = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(join(root, "bin", "cm.sha256"), `${digest}  cm\n`, "utf-8");
console.log(`Checksum manifest: bin/cm.sha256 (${digest.slice(0, 12)}…)`);

function orderSize(b) { return Buffer.byteLength(b); }
